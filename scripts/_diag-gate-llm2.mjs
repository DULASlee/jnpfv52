import { runSqlQuery } from './lib/jnpf-db.mjs';

const cols = await runSqlQuery(`
SET NOCOUNT ON;
SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME='BASE_AI_CALL_LOG' AND COLUMN_NAME LIKE '%ERR%' OR (TABLE_NAME='BASE_AI_CALL_LOG' AND COLUMN_NAME LIKE '%STATUS%') OR (TABLE_NAME='BASE_AI_CALL_LOG' AND COLUMN_NAME LIKE '%MODEL%')
ORDER BY ORDINAL_POSITION;
`);
console.log(cols);

const recent = await runSqlQuery(`
SET NOCOUNT ON;
SELECT TOP 8
  CAST(F_Id AS VARCHAR(30)) AS Id,
  ISNULL(F_SkillId,'') AS Skill,
  ISNULL(F_ACTUAL_MODEL, ISNULL(F_MODEL,'')) AS Model,
  F_STATUS_CODE AS Http,
  F_PROMPT_TOKENS AS Tin,
  F_COMPLETION_TOKENS AS Tout,
  F_LATENCY_MS AS Ms,
  LEN(ISNULL(F_RESPONSE_BODY,'')) AS RespLen,
  LEFT(ISNULL(F_RESPONSE_BODY,''), 150) AS Head,
  F_CREATOR_TIME AS Ts
FROM BASE_AI_CALL_LOG
WHERE F_CREATOR_TIME >= DATEADD(MINUTE, -45, GETDATE())
ORDER BY F_CREATOR_TIME DESC;
`);
console.log('\nrecent\n', recent);

const msg = await runSqlQuery(`
SET NOCOUNT ON;
SELECT TOP 5 F_PIPELINE_ID, F_ROLE, F_STAGE, LEN(ISNULL(F_CONTENT,'')) AS Len,
  LEFT(ISNULL(F_CONTENT,''), 400) AS Head
FROM BASE_AI_PIPELINE_MESSAGE
WHERE F_PIPELINE_ID IN ('358','357')
ORDER BY F_CREATOR_TIME DESC;
`);
console.log('\nmsgs\n', msg);

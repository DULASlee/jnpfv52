SET STATISTICS TIME ON;
SELECT * FROM ext_order_entry WHERE F_ORDER_ID IS NOT NULL;
SELECT * FROM ext_order_receivable WHERE F_ORDER_ID IS NOT NULL;
SET STATISTICS TIME OFF;

-- 权限三连查（authorize -> module -> scheme 等价）

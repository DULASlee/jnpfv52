SET NOCOUNT ON;
SET STATISTICS TIME ON;
SELECT TOP 20 a.F_ID, a.F_ORDER_CODE, a.F_CUSTOMER_NAME, b.F_REAL_NAME, b.F_ACCOUNT, c.F_STATUS
FROM ext_order a
LEFT JOIN base_user b ON a.F_CREATOR_USER_ID = b.F_ID
LEFT JOIN flow_task c ON a.F_ID = c.F_ID
WHERE a.F_DELETE_MARK IS NULL
ORDER BY a.F_CREATOR_TIME DESC;
SET STATISTICS TIME OFF;


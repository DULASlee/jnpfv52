#!/usr/bin/env node
/**
 * Harness Resolver — Executable Runtime (Phase 0.6 Task 0.6.2)
 *
 * Resolves: Resolve(User, Project, Phase, Task) -> Machine-readable JSON
 * Authority Model != Context Priority != Skill Routing != Execution Order (Phase 0.6 Condition 2)
 *
 * Input:  { userScope, projectScope, phase, taskClassification }  or CLI flags
 * Output: { authoritative, advisory, capabilities, memoryProviders, blocked, mirrors, quarantined, drift? }
 *
 * Loader MUST only accept resolver output — never direct filesystem scan.
 * Quarantine MUST NOT be part of authoritative or automatic Harness Resolution.
 *
 * Usage:
 *   node .claude/hooks/harness-resolver.mjs --phase P0 --task S
 *   node .claude/hooks/harness-resolver.mjs --json
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();

// --- Load canonical baseline (generated by harness-drift) ---
function loadBaseline() {
  const p = path.join(ROOT, '.claude/control-plane/00-governance/HARNESS-BASELINE.json');
  if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf-8'));
  return null;
}

// --- Authority pyramid (L0-L6) — Authority determines who may govern ---
const AUTHORITY = {
  L0_ImmutableLaws: { level: 100, governs: true, label: 'L0 Immutable Engineering Laws' },
  L1_ControlPlane: { level: 90, governs: true, label: 'L1 Control Plane (ONLY Governance Authority)' },
  L2_ProjectConstitution: { level: 80, governs: true, label: 'L2 Project Constitution' },
  L3_ActivePhase: { level: 70, governs: true, label: 'L3 Active Phase' },
  L4_TaskPolicy: { level: 60, governs: true, label: 'L4 Task Policy' },
  L5_ExpertSkill: { level: 50, governs: false, label: 'L5 Expert Skill (Domain)' },
  L6_ExternalAdvisory: { level: 10, governs: false, label: 'L6 External Advisory — NEVER governs' },
  Capability: { level: 0, governs: false, label: 'Capability (MCP driver)' },
  Memory: { level: 0, governs: false, label: 'Memory (Provider)' },
};

// --- Resolution vs Authority vs Execution — three separable concepts ---
const SEMANTICS = {
  authority: 'who may govern — L0-L6 pyramid, L6 cannot override L0-L5',
  resolution: 'what is loaded — scoped subset via Harness Resolver (this file)',
  execution: 'when it runs — workflow/phase/task ordering',
};

// --- Capability Registry (authoritative source: HARNESS-RESOLUTION.yaml) ---
const CAPABILITIES = {
  SymbolSearch: { provider: 'serena', enabled: true, allowedFor: ['generic-class-refactor-expert','table-refactor-expert','architecture-gate'] },
  CallGraph: { provider: 'codegraph', enabled: true },
  CodebaseMemory: { provider: 'codebase-memory', enabled: true },
  DotNetDebug: { provider: 'netcoredbg', enabled: true },
  BrowserE2E: { provider: 'playwright', enabled: true },
  ToolRouter: { provider: 'tool-search', enabled: true },
};

const MEMORY = {
  EccMemory: { provider: 'ecc-memory', path: '.ecc/memory/project' },
  KnowledgeGraph: { provider: 'knowledge-graph', path: '.ai-memory/knowledge-graph.json' },
  UnifiedMemory: { provider: 'unified-memory', path: 'C:/Users/admin/.claude/skills/unified-memory' },
  PendingIssues: { provider: 'pending-issues', path: '.claude/memory/pending-issues.md' },
};

function resolve({ phase = 'P0', taskClassification = 'A' } = {}) {
  const baseline = loadBaseline();

  // Authoritative: ONLY Control Plane + mirrored project rules + constitution
  const authoritative = [
    '.claude/control-plane/00-governance/MASTER-GOVERNANCE.md',
    '.claude/control-plane/00-governance/GOVERNANCE-INDEX.md',
    '.claude/control-plane/00-governance/L0-LAWS.md',
    '.claude/control-plane/00-governance/L1-PROJECT-RULES.md',
    '.claude/control-plane/00-governance/L2-PHASE-RULES.md',
    '.claude/control-plane/00-governance/HUMAN-GATE-RULES.yaml',
    '.claude/control-plane/01-workflows/*',
    '.claude/control-plane/02-rules/*',
    '.claude/control-plane/03-skills/*',
    '.claude/rules/** (mirrored to L1)',
    'AGENTS.md',
    'CLAUDE.md',
  ];

  // Advisory: External — MAY advise, NEVER govern
  const advisory = [
    'superpowers@5.1.0: brainstorming, systematic-debugging, verification-before-completion (Migrate candidate), ... (14 total)',
    'globalClaudeSkills: graphify, plan-canvas, strategic-compact, unified-memory, verification-loop',
    'userOpencodeSkills: agent-architecture-audit, dotnet-patterns, production-audit, prompt-optimizer, rules-distill, skill-scout, skill-stocktake',
  ];

  // Mirrors — explicit type to avoid permanent Advisory confusion
  const mirrors = [
    { path: '.cursor/rules/*.mdc', type: 'MIRROR', source: '.claude/rules/*.md', sync: 'manual (no auto-sync) — Control Plane wins on conflict', authority: 'NOT AUTHORITATIVE' },
    { path: '.cursor/skills/*', type: 'MIRROR', source: '.claude/skills/* + superpowers', sync: 'manual — ADVISORY MIRROR', authority: 'NOT AUTHORITATIVE' },
    { path: '.agents/skills/*', type: 'MIRROR', source: 'superpowers@5.1.0', sync: 'manual — Execution Mirror', authority: 'NOT AUTHORITATIVE' },
  ];

  // Capabilities and memory — providers only
  const capabilities = Object.entries(CAPABILITIES).filter(([,v])=>v.enabled).map(([k,v])=> ({ capability: k, provider: v.provider, authority: 'CAPABILITY — driver only' }));
  const memoryProviders = Object.entries(MEMORY).map(([k,v])=> ({ name: k, provider: v.provider, path: v.path, authority: 'MEMORY — provider only' }));

  // Blocked / Quarantined — MUST NOT be part of authoritative or automatic resolution
  const blocked = [
    '.ai/quarantine/**',
    '.ai/quarantine/backups/**',
    '.claude/_archived/**',
    '.superpowers/**',
    'episodic-memory@disabled',
    'double-shot-latte@disabled',
  ];

  const quarantined = blocked; // alias

  // Phase/Task scoped resolution (example — real routing uses phase-state.yaml + ROUTING-MATRIX)
  const applicableSkills = phase === 'P0' ? ['phase-management','evidence-collection'] :
                           phase === 'P1' ? ['architecture-gate','orchestration'] :
                           ['generic-class-refactor-expert','data-driven-debug'];

  return {
    version: '0.6.0',
    semantics: SEMANTICS,
    authorityPyramid: AUTHORITY,
    input: { phase, taskClassification },
    authoritative,
    advisory,
    mirrors,
    capabilities,
    memoryProviders,
    blocked,
    quarantined,
    applicableSkills,
    note: 'Quarantine MUST NOT be part of authoritative or automatic Harness Resolution (not impossible to access, but never auto-loaded).',
    gateCheck: [
      'Authoritative source unique: .claude/control-plane only',
      'Advisory cannot become Governance (L6 cannot override L0-L5)',
      'Quarantine never auto-loads (resolver excludes .ai/quarantine/**)',
      'Mirrors are NOT authoritative — Control Plane wins',
      'Capabilities are drivers only — AgentOS holds Policy',
    ],
    baselineRef: baseline ? baseline.generatedAt : null,
  };
}

// CLI — only run when executed directly, not when imported
const isMain = process.argv[1] && process.argv[1].replace(/\\/g,'/').endsWith('harness-resolver.mjs');
if (isMain) {
  const args = process.argv.slice(2);
  const getArg = (k) => {
    const i = args.indexOf(k);
    return i !== -1 ? args[i+1] : null;
  };
  if (args.includes('--help') || args.includes('-h')) {
    console.log('Usage: node .claude/hooks/harness-resolver.mjs [--phase P0] [--task S|A|B] [--json] [--out <file>]');
    process.exit(0);
  }
  const phase = getArg('--phase') || 'P0';
  const task = getArg('--task') || 'A';
  const result = resolve({ phase, taskClassification: task });

  if (args.includes('--out')) {
    const out = getArg('--out');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(result, null, 2), 'utf-8');
    console.log(`Resolver output written to ${out}`);
  } else {
    console.log(JSON.stringify(result, null, 2));
  }
}

export { resolve, AUTHORITY, SEMANTICS };
